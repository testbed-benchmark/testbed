r"""Emit per-recipe W&B seed sweeps.

Queries W&B for the seeds a recipe has already finished and writes a grid
sweep containing only the missing ones, so agents never repeat completed work.
Crashed and killed runs are not ``finished``, so re-running this rebuilds a
catch-up queue.

Be careful to only call this script after agents have finished running as 
in progress runs are not finished and so they may be falsely counted as not 
allocated yet.

The W&B project and group are read from the recipe itself (its ``wandb:``
block), so the sweep YAML cannot drift from the config. The entity is not in
the recipe (it stays ``null`` there for outside users) and comes from
``--entity`` or ``WANDB_ENTITY``.

After running this::

    # One-time: create the sweep (prints <sweep_id>)
    wandb sweep sweeps/location_finding_2src_actionbed.yaml

    # On each machine, pull seeds from the shared queue
    wandb agent <entity>/<project>/<sweep_id>

Agents on any number of machines can point at the same sweep — W&B hands each
seed out once.

Usage
-----
    export WANDB_ENTITY=rainml-testbed
    python scripts/generate_seed_sweeps.py \
        --recipe experiments/location_finding_2src/actionbed
    python scripts/generate_seed_sweeps.py \
        --recipe experiments/location_finding_2src/{actionbed,dad,rlboed} \
        --seeds 0 1 2 3 4
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

from hydra import compose, initialize_config_dir

REPO_ROOT = Path(__file__).resolve().parents[1]
RECIPES_DIR = str(REPO_ROOT / "testbed" / "recipes")


def read_wandb_target(recipe: str) -> tuple[str, str]:
    """Composes a recipe and returns its ``(project, group)``."""
    with initialize_config_dir(version_base="1.3", config_dir=RECIPES_DIR):
        cfg = compose(config_name=recipe)
    if cfg.wandb.group is None:
        raise SystemExit(
            f"{recipe} has no wandb.group; add a wandb block naming the project "
            f"(the task) and the group (the method)."
        )
    return cfg.wandb.project, cfg.wandb.group


def finished_seeds(api, entity: str, project: str, group: str) -> set[int]:
    """Returns the seeds of every finished run in a project's group."""
    runs = api.runs(f"{entity}/{project}", filters={"group": group})
    seeds = set()
    for run in runs:
        if run.state != "finished":
            continue
        seed = run.config.get("seed")
        if seed is not None:
            seeds.add(int(seed))
    return seeds


def write_sweep_yaml(
    path: Path,
    recipe: str,
    entity: str,
    project: str,
    group: str,
    missing: list[int],
    no_eval: bool = False,
) -> None:
    """Writes a grid sweep over the missing seeds."""
    seeds = ", ".join(str(seed) for seed in missing)
    task = os.path.basename(os.path.dirname(recipe))
    eval_flag = "  - --no-eval\n" if no_eval else ""
    path.write_text(
        f"# Seed sweep for {recipe}\n"
        f"# Generated by scripts/generate_seed_sweeps.py "
        f"({len(missing)} seeds still to run).\n"
        f"\n"
        f"name: {task}-{group}-seeds\n"
        f"program: scripts/sweep_run.py\n"
        f"method: grid\n"
        f"entity: {entity}\n"
        f"project: {project}\n"
        f"\n"
        f"parameters:\n"
        f"  seed:\n"
        f"    values: [{seeds}]\n"
        f"\n"
        f"command:\n"
        f"  - ${{interpreter}}\n"
        f"  - ${{program}}\n"
        f"  - --recipe\n"
        f"  - {recipe}\n"
        f"{eval_flag}"
        # ${args_no_hyphens} expands to "seed=3", i.e. Hydra override syntax, so
        # every swept parameter reaches the run the same way. Plain ${args} would
        # give "--seed=3", and ${seed} is not a wandb macro at all: it gets
        # silently stripped, leaving the recipe's default seed.
        f"  - ${{args_no_hyphens}}\n"
    )


def main() -> None:
    """Writes a sweep YAML per recipe covering its unfinished seeds."""
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--recipe",
        nargs="+",
        required=True,
        help="Recipe paths, e.g. experiments/location_finding_2src/actionbed.",
    )
    parser.add_argument("--seeds", nargs="+", type=int, default=[0, 1, 2, 3, 4])
    parser.add_argument(
        "--entity",
        default=os.environ.get("WANDB_ENTITY"),
        help="W&B team/user (default: $WANDB_ENTITY).",
    )
    parser.add_argument("--out-dir", default=str(REPO_ROOT / "sweeps"))
    parser.add_argument(
        "--no-eval",
        action="store_true",
        help="Emit sweeps that skip the post-training eval.",
    )
    args = parser.parse_args()

    if not args.entity:
        raise SystemExit(
            "no entity: pass --entity or set WANDB_ENTITY. A sweep YAML must "
            "name the entity for `wandb sweep` to reach the right project."
        )

    try:
        import wandb
    except ImportError:
        raise SystemExit('wandb is not installed — `pip install -e ".[wandb]"`')

    api = wandb.Api()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"{'recipe':<50}  done / total   yaml")
    for recipe in args.recipe:
        project, group = read_wandb_target(recipe)
        done = finished_seeds(api, args.entity, project, group)
        missing = [seed for seed in args.seeds if seed not in done]

        task = os.path.basename(os.path.dirname(recipe))
        method = os.path.basename(recipe)
        yaml_path = out_dir / f"{task}_{method}.yaml"

        if missing:
            write_sweep_yaml(
                yaml_path,
                recipe,
                args.entity,
                project,
                group,
                missing,
                no_eval=args.no_eval,
            )
            status = str(yaml_path.relative_to(REPO_ROOT))
        else:
            # Drop stale YAMLs so a finished recipe has no queue left behind.
            yaml_path.unlink(missing_ok=True)
            status = "(complete — no YAML)"
        print(
            f"{recipe:<50}  {len(args.seeds) - len(missing)}/{len(args.seeds)}"
            f"            {status}"
        )

    print("\nNext steps:")
    print("  wandb sweep sweeps/<task>_<method>.yaml        # prints <sweep_id>")
    print(f"  wandb agent {args.entity}/<project>/<sweep_id>  # on each machine")


if __name__ == "__main__":
    main()
